#!/usr/bin/env python3
"""Emit the C++ site tables from the authoritative Python definitions."""
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
import game_sites


def q(value):
    return json.dumps(value, ensure_ascii=True)


def emit():
    print('// Generated by sites_data.py from tools/game_sites.py; do not edit.')
    print('static const Version versions[] = {')
    for v in game_sites.VERSIONS:
        print(f'    {{{q(v.name)}, {q(v.build_id)}, {str(v.supported).lower()}}},')
    print('};\nstatic const Site definitions[] = {')
    for s in game_sites.SITES:
        patterns = s.pattern if isinstance(s.pattern, list) else [(s.pattern, s.at)] if s.pattern else []
        print(f'    {{{q(s.name)}, {q(s.kind)}, {{')
        for pattern, at in patterns:
            print('        {')
            words = pattern.split()
            for start in range(0, len(words), 4):
                chunk = ' '.join(words[start:start + 4])
                if start + 4 < len(words):
                    chunk += ' '
                print(f'            {q(chunk)}')
            print(f'            , {at}}},')
        print('    }},')
    print('};\nstatic const std::vector<std::vector<std::string>> optional_groups = {')
    for group in game_sites.OPTIONAL_GROUPS:
        print('    {' + ', '.join(map(q, group)) + '},')
    print('};\nstatic const std::map<std::string, std::map<std::string, U>> known = {')
    for version, entries in game_sites.KNOWN.items():
        print(f'    {{{q(version)}, {{')
        for name, value in entries.items():
            print(f'        {{{q(name)}, 0x{value:x}ULL}},')
        print('    }},')
    print('};')


if __name__ == '__main__':
    emit()
