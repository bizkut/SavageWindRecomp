#!/usr/bin/env python3
# Savage Wind PS5 - the Vulkan commands as link-time symbols, resolved through the RADV archive's ICD entry point.
# SPDX-License-Identifier: GPL-3.0-or-later
#
#   gen-vk-globals.py <vulkan_core.h> <out.c>
#
# The renderer (runtime/nvn/vulkan/*) and VMA call Vulkan commands by name, as a desktop links them from the loader.
# A title has no loader: RADV is linked whole into the eboot and exports only vk_icdGetInstanceProcAddr (the same
# situation PS5_vkQuake's platform/ps5/vk_globals.c answers for its 79 commands). This writes one trampoline per
# command of the header the renderer is compiled against; each resolves its driver function on first call, through
# the device once one exists, else the instance, else the null instance (the four global commands). Unused ones go
# with --gc-sections. A command the driver does not provide stops the title with its name instead of calling null.
# Driver time (runtime/nvn/vulkan/rprof.c, savagewind.ini render_profile = 1): while g_vk_driver_prof is set, each
# trampoline called on the thread g_vk_driver_prof_thread adds its driver call's time stamp counter ticks and a count to
# that command's entry of g_vk_driver_ticks / g_vk_driver_calls (names in g_vk_driver_names). Off: one load and branch.
import re
import sys

header, out = sys.argv[1], sys.argv[2]
text = open(header, encoding="utf-8").read()
protos = re.findall(r"VKAPI_ATTR\s+(.+?)\s+VKAPI_CALL\s+(vk\w+)\s*\(([^;]*?)\);", text, re.S)
GLOBAL = {"vkCreateInstance", "vkEnumerateInstanceExtensionProperties", "vkEnumerateInstanceLayerProperties",
          "vkEnumerateInstanceVersion"}
seen = set()
names = []
lines = [
    "// GENERATED by ps5/tools/gen-vk-globals.py from %s; do not edit." % header.split("/include/")[-1],
    "// SPDX-License-Identifier: GPL-3.0-or-later",
    "#include <pthread.h>",
    "#include <stdint.h>",
    "#include <stdlib.h>",
    "#include <vulkan/vulkan_core.h>",
    "",
    "VKAPI_ATTR PFN_vkVoidFunction VKAPI_CALL vk_icdGetInstanceProcAddr(VkInstance instance, const char *name);",
    "void ps5_logf(const char *format, ...);",
    "static VkInstance g_instance;",
    "static VkDevice g_device;",
    "static PFN_vkGetDeviceProcAddr g_device_proc;",
    "int g_vk_driver_prof;",
    "pthread_t g_vk_driver_prof_thread;",
    "extern uint64_t g_vk_driver_ticks[], g_vk_driver_calls[];",
    "",
    "static PFN_vkVoidFunction resolve(const char *name, int global) {",
    "    PFN_vkVoidFunction f = NULL;",
    "    if (global) f = vk_icdGetInstanceProcAddr(VK_NULL_HANDLE, name);",
    "    else {",
    "        if (g_device && g_device_proc) f = g_device_proc(g_device, name);",
    "        if (!f && g_instance) f = vk_icdGetInstanceProcAddr(g_instance, name);",
    "    }",
    "    if (!f) {",
    "        ps5_logf(\"[vk] RADV does not provide %s (%s)\\n\", name, g_instance ? \"instance\" : \"no instance yet\");",
    "        abort();",
    "    }",
    "    return f;",
    "}",
    "",
    "VKAPI_ATTR PFN_vkVoidFunction VKAPI_CALL vkGetInstanceProcAddr(VkInstance instance, const char *name) {",
    "    return vk_icdGetInstanceProcAddr(instance, name);",
    "}",
    "",
]
for ret, name, params in protos:
    if name in seen or name == "vkGetInstanceProcAddr":
        continue
    seen.add(name)
    params = " ".join(params.split())
    args = []
    if params != "void":
        for p in params.split(","):
            m = re.search(r"(\w+)\s*(\[[^\]]*\])?\s*$", p.strip())
            args.append(m.group(1))
    call = "%s(%s)" % ("f", ", ".join(args))
    lines.append("VKAPI_ATTR %s VKAPI_CALL %s(%s) {" % (ret, name, params))
    lines.append("    static PFN_%s p;" % name)
    lines.append("    PFN_%s f = __atomic_load_n(&p, __ATOMIC_RELAXED);" % name)
    lines.append("    if (!f) __atomic_store_n(&p, f = (PFN_%s)resolve(\"%s\", %d), __ATOMIC_RELAXED);"
                 % (name, name, name in GLOBAL))
    if name == "vkCreateInstance":
        lines += ["    VkResult r = %s;" % call, "    if (r == VK_SUCCESS) g_instance = *pInstance;", "    return r;"]
    elif name == "vkCreateDevice":
        lines += ["    VkResult r = %s;" % call,
                  "    if (r == VK_SUCCESS && !g_device) {",
                  "        g_device_proc = (PFN_vkGetDeviceProcAddr)vk_icdGetInstanceProcAddr(g_instance, \"vkGetDeviceProcAddr\");",
                  "        g_device = *pDevice;",
                  "    }",
                  "    return r;"]
    else:
        i = len(names)
        names.append(name)
        lines.append("    if (__builtin_expect(__atomic_load_n(&g_vk_driver_prof, __ATOMIC_RELAXED), 0) && "
                     "pthread_equal(pthread_self(), g_vk_driver_prof_thread)) {")
        lines.append("        uint64_t t0 = __builtin_ia32_rdtsc();")
        lines.append("        %s%s;" % ("" if ret == "void" else "%s r = " % ret, call))
        lines.append("        g_vk_driver_ticks[%d] += __builtin_ia32_rdtsc() - t0, g_vk_driver_calls[%d]++;" % (i, i))
        lines.append("        return%s;" % ("" if ret == "void" else " r"))
        lines.append("    }")
        if ret == "void":
            lines.append("    %s;" % call)
        else:
            lines.append("    return %s;" % call)
    lines.append("}")
    lines.append("")
if len(seen) < 300:
    raise SystemExit("gen-vk-globals: only %d commands parsed from %s" % (len(seen), header))
lines.append("uint64_t g_vk_driver_ticks[%d], g_vk_driver_calls[%d];" % (len(names), len(names)))
lines.append("const int g_vk_driver_count = %d;" % len(names))
lines.append("const char *const g_vk_driver_names[%d] = {" % len(names))
lines += ["    \"%s\"," % n for n in names]
lines += ["};", ""]
open(out, "w", encoding="utf-8").write("\n".join(lines))
